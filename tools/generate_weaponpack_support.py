#!/usr/bin/env python3
"""Generate Trigger Discipline wrappers for ported weapon packs.

Scans the decompiled weapon source tree, finds every fire-mode class referenced
by a weapon's FireModeClass default, and writes:

  * WeaponPacks/Classes/TriggerDisciplineWP_<Class>.uc
  * WeaponPacks/Classes/TriggerDisciplineWeaponPacksRegistry.uc

The generated package is optional: the core mutator loads its registry through
DynamicLoadObject, so the base game still works without these packs installed.

Usage:
    python3 tools/generate_weaponpack_support.py \
        /home/jdmr/Proyectos/ut2k4mutators/ut2k4weaponsdecompiled/Output
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

# Decompiled folder -> UnrealScript package name.
PACKAGES = {
    "UnrealChampionship1Weapons": "UC1Weapons",
    "UnrealChampionship2Weapons": "UC2Weapons",
    "UnrealTournament3Weapons": "UT3Style",
    "UnrealTournament99Weapons": "UT2341Weapons_BETA3",
}

# Fire modes already handled by the core package.
IGNORED_PACKAGES = {"XWeapons", "UTClassic"}

WRAPPER_PREFIX = "TriggerDisciplineWP_"
REGISTRY_CLASS = "TriggerDisciplineWeaponPacksRegistry"

CLASS_RE = re.compile(r"^\s*class\s+(\w+)\s+extends\s+([\w.]+)", re.I | re.M)
FIREMODE_RE = re.compile(r"FireModeClass\(\d\)\s*=\s*Class'([\w.]+)\.(\w+)'", re.I)

WRAPPER_TEMPLATE = """//=============================================================================
// Trigger Discipline wrapper for {package}.{name}
// Generated by tools/generate_weaponpack_support.py -- do not edit by hand.
//
// Extends the exact original class so ammo, projectiles, animations, sounds
// and all weapon-specific behaviour are inherited unchanged.
//=============================================================================
class {wrapper} extends {name};

// Every fire mode calls AdjustAim() before firing.  Most of them leave Spread
// at zero, so the spread multiplier alone would have no effect.
function Rotator AdjustAim(Vector Start, float InAimError)
{{
	return class'TriggerDisciplineMut'.static.ApplyAimDeviation(Self, Super.AdjustAim(Start, InAimError));
}}

function DoFireEffect()
{{
	local float BaseSpread, BaseAimError, BaseDamageAtten;

	BaseSpread = Spread;
	BaseAimError = AimError;
	BaseDamageAtten = DamageAtten;

	class'TriggerDisciplineMut'.static.ApplyModifiers(Self, BaseSpread, BaseAimError, BaseDamageAtten);

	Super.DoFireEffect();

	Spread = BaseSpread;
	AimError = BaseAimError;
	DamageAtten = BaseDamageAtten;
}}

defaultproperties
{{
}}
"""

REGISTRY_HEADER = """//=============================================================================
// Trigger Discipline weapon-pack registry
// Generated by tools/generate_weaponpack_support.py -- do not edit by hand.
//
// The core mutator loads this class with DynamicLoadObject.  Each entry maps an
// exact mod fire-mode class to its Trigger Discipline wrapper.
//=============================================================================
class {registry} extends TriggerDisciplineModRegistry;

function class<WeaponFire> GetModFireModeClass(class<WeaponFire> OriginalClass)
{{
	local string N;

	if (OriginalClass == None)
		return None;

	N = string(OriginalClass);

""".format(registry=REGISTRY_CLASS)

REGISTRY_FOOTER = """
	return None;
}

defaultproperties
{
}
"""


def collect(classes_root: Path):
    classes = {}
    for folder, package in PACKAGES.items():
        for path in (classes_root / folder).glob("*.uc"):
            text = path.read_text(errors="ignore")
            match = CLASS_RE.search(text)
            if not match:
                continue
            name, parent = match.group(1), match.group(2)
            classes[name] = (package, folder, parent, path)

    used = {}
    for path in classes_root.glob("*/*.uc"):
        text = path.read_text(errors="ignore")
        for package, name in FIREMODE_RE.findall(text):
            if package in IGNORED_PACKAGES:
                continue
            if package not in PACKAGES.values():
                continue
            if name not in classes:
                raise SystemExit(f"{path}: {package}.{name} was not found in the decompiled tree")
            used[name] = classes[name]

    return used


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "output",
        nargs="?",
        default="/home/jdmr/Proyectos/ut2k4mutators/ut2k4weaponsdecompiled/Output",
    )
    parser.add_argument(
        "--target",
        default=str(Path(__file__).resolve().parent.parent / "WeaponPacks" / "Classes"),
    )
    args = parser.parse_args()

    classes_root = Path(args.output)
    target = Path(args.target)
    target.mkdir(parents=True, exist_ok=True)

    used = collect(classes_root)
    if not used:
        raise SystemExit("No custom fire modes found")

    for old in target.glob(f"{WRAPPER_PREFIX}*.uc"):
        old.unlink()

    mappings = []
    for name in sorted(used):
        package, _folder, _parent, _path = used[name]
        wrapper = WRAPPER_PREFIX + name
        (target / f"{wrapper}.uc").write_text(
            WRAPPER_TEMPLATE.format(package=package, name=name, wrapper=wrapper)
        )
        mappings.append(f'\tif (N == "{package}.{name}") return class\'{wrapper}\';')

    registry = REGISTRY_HEADER + "\n".join(mappings) + REGISTRY_FOOTER
    (target / f"{REGISTRY_CLASS}.uc").write_text(registry)

    print(f"Generated {len(used)} wrappers and {REGISTRY_CLASS}.uc in {target}")
    for name in sorted(used):
        print(f"  {used[name][0]}.{name}")


if __name__ == "__main__":
    main()
